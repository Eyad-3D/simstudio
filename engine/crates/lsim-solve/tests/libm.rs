//! The platform's mathematical library is within an ulp of the exact
//! value: the interval enclosures that search conditions on functions of
//! time ahead (`lsim-solve/src/interval.rs`) widen what `sin`, `cos`,
//! `exp`, `ln` (and `tan`, `asin`, `acos`, `atan`, `sinh`, `cosh`, `tanh`,
//! `powf`) return by 2 ulps, which holds them only if each is within 1 ulp
//! of the exact value. glibc's are; another platform's (Windows, macOS)
//! may not be, and this test says so there.
//!
//! The references are the correctly rounded values at 543 fixed points
//! (sines and cosines from −12 to 1e5, exponentials from −40 to 700,
//! logarithms from 1e-8 to 1e8), computed in 110-digit decimal arithmetic
//! (Python's `decimal`: `exp` and `ln` built in, sine and cosine by their
//! series after reducing the argument by 2π to 110 digits). A function
//! within 1 ulp of the exact value is within 1 ulp of the correctly
//! rounded one, as this checks (glibc matches every one exactly).

#[test]
fn the_platforms_libm_is_within_an_ulp() {
    let mut worst: Vec<(&str, f64, f64)> = vec![];
    for &(name, x, r) in REFERENCES {
        let (x, r) = (f64::from_bits(x), f64::from_bits(r));
        let v = match name {
            "sin" => x.sin(),
            "cos" => x.cos(),
            "exp" => x.exp(),
            "ln" => x.ln(),
            _ => unreachable!(),
        };
        let ok = v == r || v == r.next_up() || v == r.next_down();
        if !ok {
            worst.push((name, x, v));
        }
    }
    assert!(
        worst.is_empty(),
        "the platform's libm is more than 1 ulp from the exact value (the interval enclosures \
         need a wider margin): {worst:?}"
    );
}

