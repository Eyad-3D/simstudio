"""Exact answers out of Python, for engines and ports that do not run it.

    python -m benchmarks.reference.export --checkpoints
        rewrites the [checkpoints] section at the end of every problem file:
        the events and every compared signal and energy term at a quarter,
        half, three quarters and the end of the run, so a port of exact.py
        (or an engine's own test) can check itself against the TOML alone.
    python -m benchmarks.reference.export --json DIR
        writes DIR/<id>.json: every compared quantity at every output time.

tests/test_reference_problems.py checks that the checkpoints match exact.py.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from . import Problem, load_all
from .exact import solve

MARKER = "# ---- checkpoints: generated by `python -m benchmarks.reference.export --checkpoints`"


def quantities(problem: Problem) -> list[str]:
    """The signals and energy terms a problem compares or balances, in order."""
    names = [c.name for c in problem.compare if c.kind != "event"]
    return names + [n for n in problem.energy_terms if n not in names]


def checkpoint_times(problem: Problem) -> list[float]:
    grid = problem.output_times()
    n = len(grid) - 1
    return [grid[round(n * k / 4)] for k in (1, 2, 3, 4)]


def checkpoints(problem: Problem) -> dict:
    ex = solve(problem)
    times = checkpoint_times(problem)
    out = {"times": times}
    for name in quantities(problem):
        out[name] = [ex.at(name, t) for t in times]
    out["events"] = {c.name: ex.events[c.name] for c in problem.compared("event")}
    return out


def _toml_list(values: list[float]) -> str:
    return "[" + ", ".join(repr(float(v)) for v in values) + "]"


def checkpoint_text(problem: Problem) -> str:
    cp = checkpoints(problem)
    lines = [MARKER, "# (the exact answer at these times, to the last digit; edit the problem, "
             "then regenerate)", "[checkpoints]", f"times = {_toml_list(cp['times'])}"]
    lines += [f"{name} = {_toml_list(cp[name])}" for name in quantities(problem)]
    if cp["events"]:
        lines += ["", "[checkpoints.events]"]
        lines += [f"{k} = {float(v)!r}" for k, v in cp["events"].items()]
    return "\n".join(lines) + "\n"


def write_checkpoints(problem: Problem) -> bool:
    """Rewrite a problem file's checkpoint section; True if it changed."""
    text = problem.path.read_text(encoding="utf-8")
    head = text.split(MARKER)[0].rstrip("\n") + "\n\n"
    new = head + checkpoint_text(problem)
    if new != text:
        problem.path.write_text(new, encoding="utf-8")
        return True
    return False


def export_json(problem: Problem, folder: Path) -> Path:
    ex = solve(problem)
    times = problem.output_times()
    data = {"id": problem.id, "version": problem.version, "t": times,
            "signals": {n: [ex.at(n, t) for t in times] for n in quantities(problem)},
            "events": ex.events, "breaks": ex.breaks}
    path = folder / f"{problem.id}.json"
    path.write_text(json.dumps(data), encoding="utf-8")
    return path


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--checkpoints", action="store_true")
    ap.add_argument("--json", type=Path)
    args = ap.parse_args()
    for prob in load_all():
        if args.checkpoints:
            print(f"{prob.id}: {'updated' if write_checkpoints(prob) else 'unchanged'}")
        if args.json:
            args.json.mkdir(parents=True, exist_ok=True)
            print(export_json(prob, args.json))


if __name__ == "__main__":
    main()
